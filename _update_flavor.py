all_files = [
    ("common.json", common_updates),
    ("mugwan.json", mugwan_updates),
    ("mungwan.json", mungwan_updates),
    ("dosa.json", dosa_updates),
    ("gisaeng.json", gisaeng_updates),
    ("seungbyeong.json", seungbyeong_updates),
    ("uinyeo.json", uinyeo_updates),
]

total = 0
for fname, updates in all_files:
    fpath = os.path.join(BASE, fname)
    with open(fpath, "r", encoding="utf-8") as f:
        data = json.load(f)

    updated_count = 0
    for card in data["cards"]:
        card_id = card["id"]
        if card_id in updates:
            ft = card.get("flavor_text")
            if ft and ft.get("ko"):
                card["flavor_text"]["ko"] = updates[card_id]
                updated_count += 1

    with open(fpath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")

    # Validate JSON by re-reading
    with open(fpath, "r", encoding="utf-8") as f:
        json.load(f)

    print(f"{fname}: {updated_count} cards updated (JSON valid)")
    total += updated_count

print(f"\nTotal: {total} flavor texts updated across all files.")
